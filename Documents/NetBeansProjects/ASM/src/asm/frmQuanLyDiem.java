       public void searchStudent() {
    String masvTim = txtTimSV.getText().trim();

    if (masvTim.isEmpty()) {
        JOptionPane.showMessageDialog(null, "Vui long nhap ma sinh vien can tim!");
        return;
    }

    int index = -1; 

    for (int i = 0; i < st.size(); i++) {
        if (st.get(i).Masv.trim().equalsIgnoreCase(masvTim)) { 
            index = i;
            break;
        }
    }

    if (index != -1) {
        Student sv = st.get(index);
        tblTable.setRowSelectionInterval(index, index); 
        dis(index); 

        // Hiển thị thông tin sinh viên chi tiết
        String message = "Ma SV: " + sv.Masv + "\n" +
                         "Ho Ten: " + sv.name + "\n" +
                         "Tieng Anh: " + sv.Tienganh + "\n" +
                         "Tin Hoc: " + sv.Tinhoc + "\n" +
                         "GDTC: " + sv.GDTC + "\n" +
                         "Điem TB: " + sv.DiemTb;

        JOptionPane.showMessageDialog(null, message, "Thong tin sinh vien", JOptionPane.INFORMATION_MESSAGE);
    } else {
        JOptionPane.showMessageDialog(null, "Khong tim thay sinh vien co ma: " + masvTim);
    }
}

