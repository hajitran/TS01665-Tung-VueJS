    public void loadDataToArray() {
    try {
        Class.forName("com.microsoft.sqlserver.jdbc.SQLServerDriver"); 
        Connection conn = DriverManager.getConnection(url, userName, password); 
        String sql = "select * from GRADE"; 
        Statement stm = conn.createStatement(); 
        ResultSet rs = stm.executeQuery(sql); 
        st.clear(); 
        while (rs.next()) {
            Student sv = new Student(); 
            sv.setMasv(rs.getString("MaSV")); 
            sv.setName(rs.getString("Hoten")); 
            sv.setTienganh(rs.getInt("Tienganh")); 
            sv.setTinhoc(rs.getInt("Tinhoc")); 
            sv.setGDTC(rs.getInt("GDTC")); 
            sv.setDiemTb(rs.getInt("DiemTB")); 
            st.add(sv);
        }
        conn.close();
    } catch (Exception e) { 
        System.out.println(e); 
        }
    }
    
    public void addStudent(){
    Student sv = new Student();
    sv.Masv=txtMaSV.getText();
    sv.name=txtHoTen.getText();
    sv.Tienganh= Double.parseDouble(txtTiengAnh.getText());
    sv.Tinhoc= Double.parseDouble(txtTinHoc.getText());
    sv.GDTC= Double.parseDouble(txtGDTC.getText());
    st.add(sv);
    fillToTable();
    printsv();

    }
    
      public void fillToTable(){
        String[]headers= {"Ma SV", " Ho Ten","Tieng anh","Tin hoc", " GDTC", " Diem TB"};
        DefaultTableModel model=new DefaultTableModel(headers,0);
        
        for (Student s:st) {
            Object[]row= new Object[]{s.getMasv(), s.getName(), s.getTienganh(),
                s.getTinhoc(), s.getGDTC(), s.getDiemTb()};
            model.addRow(row);
        }
        tblTable.setModel(model);
    }
    public void showDetail(){
        int index= tblTable.getSelectedRow();
        Student s=st.get(index);
        
        txtMaSV.setText(s.getMasv());
        txtHoTen.setText(s.getName());
        txtTiengAnh.setText(String.valueOf(s.Tienganh));
        txtTinHoc.setText(String.valueOf(s.Tinhoc));
        txtGDTC.setText(String.valueOf(s.GDTC));
    }
    
      public void removeStudent(){
        int index=tblTable.getSelectedRow();
        st.remove(index);
        
    }
      
      public void updateStudent(){
        int index= tblTable.getSelectedRow();
         if (index == -1) {
        JOptionPane.showMessageDialog(null, "Vui long chon sinh vien can cap nhat!");
        return;
    }
        Student s=st.get(index);
        s.setMasv(txtMaSV.getText());
        s.setName(txtHoTen.getText());
        s.setTienganh(Double.parseDouble(txtTiengAnh.getText()));
        s.setTinhoc(Double.parseDouble(txtTinHoc.getText()));
        s.setGDTC(Double.parseDouble(txtGDTC.getText()));
        
        fillToTable();
         JOptionPane.showMessageDialog(null, "Cap nhat sinh vien thanh cong!");
    }
