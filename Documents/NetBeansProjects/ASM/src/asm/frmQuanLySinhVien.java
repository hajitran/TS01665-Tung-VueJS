    public boolean ValidateFQLSV(){
        
        StringBuilder sb = new StringBuilder();
        //kiem tra masv
        if (txtMaSV.getText().equals("")) {
            sb.append("ban chua nhap masv. \n");
            txtMaSV.setBackground(Color.red);
        }
        //kiem tra ho ten
        if (txtHoTen.getText().equals("")) {
            sb.append("ban chua nhap ho ten. \n");
            txtHoTen.setBackground(Color.red);
        }
        
        //kiem tra email
        if (txtEmail.getText().equals("")) {
            sb.append("ban chua nhap email. \n");
            txtEmail.setBackground(Color.red);
        }
        
        //kiem tra dia chi
        if (txtDiaChi.getText().equals("")) {
            sb.append("ban chua nhap dia chi. \n");
            txtDiaChi.setBackground(Color.red);
        }
        
        //kiem tra dien thoai
        if (txtSDT.getText().equals("")) {
            sb.append("ban chua nhap so dien thoai. \n");
            txtSDT.setBackground(Color.red);
        }
        
        if (sb.length() > 0) {
            JOptionPane.showMessageDialog(this, sb.toString(), "Loi", JOptionPane.ERROR_MESSAGE);
            txtMaSV.setBackground(Color.white);
            txtHoTen.setBackground(Color.white);
            txtEmail.setBackground(Color.white);
            txtDiaChi.setBackground(Color.white);
            txtSDT.setBackground(Color.white);
            return false;
        }
        return true;
    }
   

