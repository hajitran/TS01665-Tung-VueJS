    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:    
        if (ValidateFQLSV()) {
            //tao doi tuong sinh vien
            SinhVien sv = new SinhVien();
            sv.setMaSV(txtMaSV.getText());
            sv.setHoTen(txtHoTen.getText());
            sv.setDiaChi(txtDiaChi.getText());
            sv.setDienthoai(txtSDT.getText());
            sv.setEmail(txtEmail.getText());
            sv.setGioiTinh(rdoNam.isSelected());
            sv.setHinh(imagePath);
        //goi them ham SinhVienDAO            
            if (svDao.add(sv)==-1) {
            JOptionPane.showMessageDialog(this, "Da ton tai MaSV","Loi!",JOptionPane.ERROR_MESSAGE);
            }else JOptionPane.showMessageDialog(this, "Them thanh cong");
            
            fillTotable();
        }        
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        if (ValidateFQLSV()) {
            //khoi tao doi tuong sv
            SinhVien sv = new SinhVien();
            sv.setHoTen(txtHoTen.getText());
            sv.setDiaChi(txtDiaChi.getText());
            sv.setDienthoai(txtSDT.getText());
            sv.setEmail(txtEmail.getText());
            sv.setGioiTinh(rdoNam.isSelected());
            sv.setHinh(imagePath);
            if (svDao.update(sv)) {
                JOptionPane.showMessageDialog(this, "Da cap nhat thanh cong");
                fillTotable();
                btnNewActionPerformed(evt);
            }else JOptionPane.showMessageDialog(this, "MaSV khong ton tai");
            
        }
        
        fillTotable();
        btnNewActionPerformed(evt);
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        String masv = txtMaSV.getText().trim();
        if (masv.equals("")) {
            JOptionPane.showMessageDialog(this, "Ban chua nhap ma SV");
            return;
        }
        if (svDao.del(masv)) {
            JOptionPane.showMessageDialog(this, "Xoa thanh cong");
            fillTotable();
        }else JOptionPane.showMessageDialog(this, "Khong ton tai MaSV de xoa");
        
        btnNewActionPerformed(evt);
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void tblStudentMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblStudentMouseClicked
        // TODO add your handling code here:
        int selectedRow = tblStudent.getSelectedRow();
    
    if(selectedRow >= 0){
        String maSV = (String)tblStudent.getValueAt(selectedRow, 0);
        
        for (SinhVien item : ds) {
            if (maSV.equals(item.getMaSV())) {
                txtMaSV.setText(item.getMaSV());
                txtHoTen.setText(item.getHoTen());
                txtDiaChi.setText(item.getDiaChi());
                txtSDT.setText(item.getDienthoai());
                txtEmail.setText(item.getEmail());
                
                // Xử lý giới tính
                if(item.isGioiTinh()) {
                    rdoNam.setSelected(true);
                } else {
                    rdoNu.setSelected(true);
                }
                
                // Hiển thị hình ảnh
                try {
                    imagePath = item.getHinh();
                    if(imagePath != null && !imagePath.isEmpty()) {
                        int rong = lblHinh.getWidth();
                        int cao = lblHinh.getHeight();
                        ImageIcon icon = new ImageIcon(
                            new ImageIcon(imagePath).getImage()
                                .getScaledInstance(rong, cao, Image.SCALE_SMOOTH)
                        );
                        lblHinh.setIcon(icon);
                    } else {
                        lblHinh.setIcon(null);
                    }
                } catch (Exception e) {
                    lblHinh.setIcon(null);
                    JOptionPane.showMessageDialog(this, "Lỗi khi tải ảnh: " + e.getMessage());
                }
                break;
            }
        }
    }         
    }//GEN-LAST:event_tblStudentMouseClicked

    private void lblHinhMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_lblHinhMouseClicked
        // TODO add your handling code here:
    JFileChooser fileChooser = new JFileChooser();
    fileChooser.setFileFilter(new FileNameExtensionFilter("Hình ảnh", "jpg", "png", "jpeg"));
    int returnValue = fileChooser.showOpenDialog(this);
    if (returnValue == JFileChooser.APPROVE_OPTION) {
        File selectedFile = fileChooser.getSelectedFile();
        imagePath= selectedFile.getAbsolutePath();
        try {
            int rong = lblHinh.getWidth();
            int cao = lblHinh.getHeight();
            ImageIcon icon = new ImageIcon(
                new ImageIcon(imagePath).getImage()
                    .getScaledInstance(rong, cao, Image.SCALE_SMOOTH)
            );
            lblHinh.setIcon(icon);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Lỗi khi tải ảnh: " + e.getMessage());
            }
        }       
    }//GEN-LAST:event_lblHinhMouseClicked

